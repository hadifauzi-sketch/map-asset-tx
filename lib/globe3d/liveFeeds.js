// Keyless sources used by the "Reference feeds" layers.
// Each function fetches only while its layer is switched on and returns plain
// objects; nothing is stored in Supabase.

import { parseRainRadarFrames } from './rainRadar.js';

async function fetchJson(url, options = {}) {
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), options.timeoutMs ?? 30000);
  // The caller's signal (layer switched off) and the timeout both cancel the request.
  const onCallerAbort = () => controller.abort();
  if (options.signal?.aborted) {
    controller.abort();
  }
  options.signal?.addEventListener('abort', onCallerAbort, { once: true });
  try {
    const response = await fetch(url, { ...options, signal: controller.signal });
    if (!response.ok) {
      throw new Error(`${response.status} ${response.statusText || 'request failed'}`);
    }
    return await response.json();
  } finally {
    window.clearTimeout(timeout);
    options.signal?.removeEventListener('abort', onCallerAbort);
  }
}

/**
 * Power stations in Malaysia from the WRI Global Power Plant Database (v1.3.0,
 * 2021, CC BY 4.0). The file is generated by scripts/build-power-plants.mjs and
 * served with the app, so this layer needs no third-party request.
 */
export async function fetchPowerPlants(signal) {
  const plants = await fetchJson(`${import.meta.env.BASE_URL}data/power-plants-mys.json`, { signal });
  return (Array.isArray(plants) ? plants : []).map((plant) => ({
    id: plant.id,
    latitude: plant.latitude,
    longitude: plant.longitude,
    name: plant.name || 'Power station',
    country: plant.country || 'Malaysia',
    fuel: plant.fuel || '',
    otherFuels: Array.isArray(plant.otherFuels) ? plant.otherFuels : [],
    capacityMw: Number.isFinite(plant.capacityMw) ? plant.capacityMw : null,
    output: plant.capacityMw ? `${plant.capacityMw.toLocaleString()} MW` : '',
    owner: plant.owner || '',
    operator: plant.owner || '',
    commissioned: plant.commissioned || '',
    source: plant.source || '',
    url: plant.url || '',
    reportedGeneration: plant.reportedGeneration || null,
    estimatedGeneration: plant.estimatedGeneration || null,
  }));
}

/** USGS earthquakes, magnitude 2.5+, past 7 days, worldwide. */
export async function fetchEarthquakes(signal) {
  const data = await fetchJson(
    'https://earthquake.usgs.gov/earthquakes/feed/v1.0/summary/2.5_week.geojson',
    { signal }
  );

  return (data?.features || [])
    .map((feature) => {
      const [longitude, latitude, depthKm] = feature.geometry?.coordinates || [];
      if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) {
        return null;
      }
      return {
        id: feature.id,
        latitude,
        longitude,
        depthKm,
        magnitude: feature.properties?.mag ?? null,
        place: feature.properties?.place || '',
        time: feature.properties?.time || null,
      };
    })
    .filter(Boolean);
}

/** RainViewer radar frame list (~2 h of past frames, oldest first). */
export async function fetchRainRadarFrames(signal) {
  const data = await fetchJson('https://api.rainviewer.com/public/weather-maps.json', { signal });
  const parsed = parseRainRadarFrames(data);
  if (!parsed.host || !parsed.frames.length) {
    throw new Error('No radar frame available');
  }
  return parsed;
}
